// Embeds pkg/sim_bg.wasm as base64 so the sim loads synchronously everywhere (browser, Vite,
// Node) with no fetch, URL or bundler plugin. Run by build.sh.
import { readFileSync, writeFileSync } from 'node:fs';

const pkg = new URL('./pkg/', import.meta.url);
const b64 = readFileSync(new URL('sim_bg.wasm', pkg)).toString('base64');
writeFileSync(
  new URL('sim_inline.js', pkg),
  `// Generated by packages/sim-wasm/inline.mjs from sim_bg.wasm. Do not edit.\nexport const wasmBase64 = "${b64}";\n`,
);
writeFileSync(
  new URL('sim_inline.d.ts', pkg),
  '/** pkg/sim_bg.wasm, base64. */\nexport declare const wasmBase64: string;\n',
);
