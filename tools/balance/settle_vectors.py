"""Write payout parity vectors for crates/sim (tests/settle_parity.rs) from settle_fuzz.settle.

Run from the repo root:  python3 tools/balance/settle_vectors.py
Each line: dep_a dep_b dead_a dead_b gold_a gold_b -> out_a out_b treasury   (dead: 0/1)
"""
import pathlib
import random
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from settle_fuzz import random_case, settle  # noqa: E402

OUT = pathlib.Path(__file__).parents[2] / "crates/sim/tests/settle_vectors.txt"
S = 1_000_000_000


def cases():
    # SPEC section 8 table.
    yield S, S, False, True, 300, 900
    yield S, S, False, False, 900, 600
    yield S, S, False, False, 650, 700
    yield S, S, False, False, 500, 500
    # Edges: double death, no gold, free match, unequal deposits, odd lamports, 1-gold margins,
    # all the gold on one side, huge gold.
    yield S, S, True, True, 900, 100
    yield S, S, False, False, 0, 0
    yield 0, 0, True, False, 0, 0
    yield 0, 50_000_000, False, False, 700, 100
    yield 3, 2, False, False, 1, 0
    yield 250_000_000, 100_000_000, False, False, 1_001, 1_000
    yield 100_000_001, 100_000_003, False, False, 0, 4_294_967_295
    yield 100_000_000, 100_000_000, True, False, 9_999, 0
    yield 18_446_744_073, 18_446_744_073, False, False, 4_294_967_295, 4_294_967_294
    # Random, with settle_fuzz's distribution (seeded, so the file is stable).
    rng = random.Random(1)
    for _ in range(3000):
        yield random_case(rng)


def main():
    lines = ["# generated by tools/balance/settle_vectors.py from settle_fuzz.settle (SPEC v3 section 8)"]
    for da, db, xa, xb, ga, gb in cases():
        o = settle(da, db, xa, xb, ga, gb)
        assert o["a"] + o["b"] + o["treasury"] == da + db
        lines.append(f"{da} {db} {int(xa)} {int(xb)} {ga} {gb} -> {o['a']} {o['b']} {o['treasury']}")
    OUT.write_text("\n".join(lines) + "\n", newline="\n")
    print(f"wrote {len(lines) - 1} vectors to {OUT}")


if __name__ == "__main__":
    main()
