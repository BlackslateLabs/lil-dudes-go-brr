"""Write payout parity vectors for crates/sim (tests/settle_parity.rs) from settle_fuzz.settle.

Only the no-Double path (Double-or-Toll is a stretch goal and not in the sim yet).
Run from the repo root:  python3 tools/balance/settle_vectors.py
Each line: dep_a dep_b hp_a hp_b -> out_a out_b treasury
"""
import pathlib
import random
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from settle_fuzz import HP_MAX, settle  # noqa: E402

OUT = pathlib.Path(__file__).parents[2] / "crates/sim/tests/settle_vectors.txt"


def cases():
    # SPEC §7 table and settle_fuzz's examples (no raise).
    yield 20_000_000, 20_000_000, 900, 0
    yield 20_000_000, 20_000_000, 1320, 880
    yield 20_000_000, 20_000_000, 1122, 1078
    yield 20_000_000, 20_000_000, 1320, 1320
    # Edges: free match, unequal deposits, 1-HP margins, full HP vs 1 HP, odd lamports.
    yield 0, 0, 2200, 0
    yield 0, 20_000_000, 1500, 700
    yield 2, 3, 2200, 1
    yield 500_000_000, 100_000_000, 2200, 2199
    yield 100_000_001, 100_000_003, 1, 2200
    yield 100_000_000, 100_000_000, 0, 1
    # Random, with settle_fuzz's distribution (seeded, so the file is stable).
    rng = random.Random(1)
    for _ in range(3000):
        da = 2 * rng.choice([0, 1, 5, 6, 10, 11, 20]) * 1_000_000 + 2 * rng.randrange(0, 1_000_000)
        db = 2 * rng.choice([0, 1, 5, 6, 10, 11, 20]) * 1_000_000 + 2 * rng.randrange(0, 1_000_000)
        ha, hb = rng.randrange(0, HP_MAX + 1), rng.randrange(0, HP_MAX + 1)
        if rng.random() < 0.2:
            ha = 0 if rng.random() < 0.5 else ha
        if ha == 0 and hb == 0:
            hb = 1
        yield da, db, ha, hb


def main():
    lines = [f"# generated by tools/balance/settle_vectors.py from settle_fuzz.settle (HP_MAX={HP_MAX})"]
    for da, db, ha, hb in cases():
        o = settle(da, db, ha, hb, False, None)
        assert o["a"] + o["b"] + o["treasury"] == da + db
        lines.append(f"{da} {db} {ha} {hb} -> {o['a']} {o['b']} {o['treasury']}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(lines) - 1} vectors to {OUT.relative_to(pathlib.Path.cwd())}")


if __name__ == "__main__":
    main()
